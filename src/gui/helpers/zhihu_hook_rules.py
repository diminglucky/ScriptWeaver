"""Reusable hook-opening rules for Zhihu-style story prompts."""

from __future__ import annotations


def build_zhihu_hook_opening_rules(*, first_section: bool = True) -> str:
    """Return hard constraints for a high-retention opening."""
    scope = "整篇故事开头/第一章开头" if first_section else "本章开头"
    return (
        f"- {scope}第一句必须直接抛出强钩子，优先使用：反常事实、危险结果、关系爆雷、死亡通知、身份错位、倒计时、不可逆后果、监控/证据异常之一。\n"
        "- 前 150 字禁止写天气、环境铺陈、人物履历、世界观解释、普通日常、作者旁白式总结；必须先让读者看到异常、冲突或代价。\n"
        "- 第一段必须抛出一个具体问题：谁在撒谎、发生了什么不可能的事、主角马上会失去什么、某段关系为什么突然崩掉，至少命中其一。\n"
        "- 前 300 字必须完成“异常出现 -> 主角即时反应 -> 更大的疑问/代价浮出”的节奏，不要把悬念留到几百字之后。\n"
        "- 异常必须落在可验证的生活证据上（手机消息、照片、监控、门锁、病历、时间点或亲密关系中的一句话）；不要只写‘我感到害怕’。\n"
        "- 首段优先交代‘谁遇到了什么’和‘马上会失去什么’，用一个具体时间/地点/物件固定读者视线，避免抽象形容词堆叠。\n"
        "- 知乎悬疑回答常见的有效节奏是短段落、动作或对话带信息；每段至少新增证据、选择、关系变化三者之一。\n"
        "- 可以借鉴知乎故事的开场感：像亲历者突然说出一个无法忽视的事实，但不要写成空泛标题党或营销号口吻。\n"
        "- 开头句式参考方向：收到一条不该存在的消息；所有人都否认某个人来过；主角发现自己的身份/记忆/亲密关系有一个致命漏洞；一个倒计时已经开始且无法取消。\n"
        "- 如果开头三句话删掉后不影响理解，说明开头太慢，必须改成直接进入事件现场。"
    )


def build_zhihu_section_opening_rules(*, section_index: int) -> str:
    """Return opening rules tuned for first vs later generated sections."""
    if section_index <= 0:
        return build_zhihu_hook_opening_rules(first_section=True)
    return (
        "- 本章第一句必须承接上章最后一个动作/情绪/发现，并立即给出新的压力、反证、代价或关系变化。\n"
        "- 禁止用“第二天、后来、与此同时、他想起了”这类跳转式软开头，除非上章结尾已经明确需要时间跳跃。\n"
        "- 前 120 字必须同时做到：接住上章悬念、推进一个新动作、制造一个比上章更大的问题。\n"
        "- 不要重新解释前情；读者已经知道的内容只允许通过动作、对话或新证据顺手带出。"
    )


def build_zhihu_high_score_story_contract(
    *, stage: str, section_index: int = 0, total_sections: int = 1
) -> str:
    """Turn recurring high-engagement Zhihu suspense patterns into an executable contract."""
    normalized_stage = str(stage or "story").strip().lower()
    if normalized_stage == "outline":
        return (
            "- 蓝图必须安排一条可验证证据链：生活异常 → 人物否认/误判 → 第二份证据 → 关系或身份代价 → 现场验证。\n"
            "- 每章写清四件事：主角当下想要什么、谁/什么阻拦、主角采取什么动作、动作造成什么不可逆后果。\n"
            "- 每章结尾只留一个主钩子，下一章先回收它，再升级到更具体的新证据；不要靠不断增加陌生设定拖延。\n"
            "- 高潮不靠解释堆叠，而靠证据迫使主角改变行动；最终章必须把开头物件/时间点/一句话重新解释。"
        )
    if normalized_stage == "section":
        position = f"第 {section_index + 1}/{max(1, total_sections)} 节"
        return (
            f"- {position}必须推进同一条证据链：本节新增证据、主角验证动作、判断变化、具体代价，四项缺一不可。\n"
            "- 证据优先通过人物行动和对话出现：翻照片、核时间、找邻居、打电话、调监控、当面试探；不要用作者旁白直接宣布真相。\n"
            "- 允许读者比主角多知道半步，但不允许信息凭空出现；每次反转都要能回看前文找到一处可解释的细节。\n"
            "- 段落以 1-3 句为主，长段只用于关键动作；每 3-5 段必须发生一次信息、关系或选择变化。\n"
            "- 结尾留下可执行的下一步或迫在眉睫的后果，不用‘我感觉事情不简单’这类空泛悬念。"
        )
    return (
        "- 采用第一人称有限视角：只写主角此刻看到、听到、记得或能验证的内容，不提前替读者解释幕后真相。\n"
        "- 开场先给一个普通而具体的生活目标/代价，再让异常破坏它；这样恐惧来自熟悉生活被改写，而不是凭空出现鬼怪。\n"
        "- 故事按‘异常证据 → 主角采取行动 → 得到更糟的证据 → 亲密关系失真 → 被迫做选择’递进；每次升级都改变下一步行动。\n"
        "- 段落以 1-3 句为主，多用动作、对话和可核对细节；解释必须晚于证据，且不能连续超过两段。\n"
        "- 结尾同时完成三件事：交代核心因果、让主角付出关系/身份/安全中的真实代价、回扣开头的物件或时间点；开放只留余味，不留硬伤。"
    )
