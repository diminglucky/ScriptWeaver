"""Zhihu-style article title rules."""

from __future__ import annotations


def build_zhihu_title_prompt(
    *,
    story_summary: str,
    min_len: int,
    max_len: int,
    banned_phrase_preview: str,
) -> str:
    """Build a high-retention title-generation prompt for Zhihu stories."""
    return f"""请为以下故事生成一个更像知乎爆款故事的标题。

目标：标题第一眼就要让人想点开，但不能像营销号。

生成流程（在脑中完成，不要输出过程）：
1. 先找出故事里最强的爆点：反常事实、身份错位、关系爆雷、死亡/危险通知、不可逆后果、监控/证据异常、主角将失去什么。
2. 生成 8 个候选标题，分别覆盖“反常事实型 / 悬念提问型 / 关系爆雷型 / 后果倒挂型 / 第一人称亲历型”。
3. 自评哪个标题最有点击欲、最具体、最贴故事，然后只输出最终标题。

硬性要求：
1. {min_len}-{max_len}字，超过{max_len}字必须压缩。
2. 必须包含一个具体钩子，不能只写情绪或主题。
3. 优先使用第一人称亲历感，像“我发现/我收到/所有人都说/镜子里的人/那条消息”这类入口。
4. 可以使用疑问句，但问题必须具体，例如“镜子里的人为什么比我先哭？”这类，不要写“真相是什么？”这种空问题。
5. 标题必须让读者立刻知道有异常、有代价、有悬念，不能平铺直叙剧情。
6. 禁止营销号夸张词：震惊、逆天、看哭了、绝了、炸裂、全网、疯传。
7. 不要使用“{banned_phrase_preview}”这类模板化表达。
8. 只返回标题文本，不要附加解释、编号、引号。

好标题方向示例（仅学习力度，不要照抄）：
- 收到自己的死亡通知后，所有人都说我早就死了
- 镜子里的人先我一步开口，喊出了我的名字
- 她明明没来过，可监控里一直站在我身后
- 我醒来后发现，家里人都在假装认识我

故事内容摘要：
{story_summary}

请直接输出最终标题："""
