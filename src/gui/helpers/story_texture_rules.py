"""Rules for making generated stories feel lived-in and compelling."""

from __future__ import annotations


def build_story_texture_rules(*, stage: str = "story") -> str:
    """Return craft constraints for realism, texture, and reader pull."""
    scope = "整篇故事" if stage == "story" else "本章"
    return (
        f"- {scope}必须像一个亲历者在讲真实发生过的事：关键场景至少落到时间、地点、空间位置、可触摸物件、声音、气味、身体反应中的三项，不能只写概念和情绪判断。\n"
        "- 人物反应禁止停留在“震惊、痛苦、感动、崩溃”等抽象词，必须写成可看见的动作、语气、停顿、回避、手部细节或说漏嘴。\n"
        "- 每 300-500 字至少放入一个可验证细节：聊天记录、票据、监控、伤口、旧物、口头禅、错记的日期、环境噪声、手机电量、门牌号、衣物褶皱等。\n"
        "- 每 4-6 段必须推进一次新信息、新阻力、新选择或新代价；禁止连续两段只解释背景、回忆往事或抒发感慨。\n"
        "- 主要人物都要有自己的立场、私心和害怕失去的东西；对话要有潜台词，不要让人物轮流替作者解释剧情。\n"
        "- 情绪要先压住再爆发：把委屈、害怕、嫉妒、愧疚写进犹豫、闪躲、重复某个细节、突然改口、强行镇定，而不是直接喊口号。\n"
        "- 反转和高潮必须造成真实代价：改变关系、身份处境、证据状态、行动空间或心理防线，不能只是发现真相但人物处境没有变化。\n"
        "- 紧张段落用短句和动作快切；情感段落可以放慢，但每一段仍要带出新的信息、关系变化或无法撤回的决定。"
    )
